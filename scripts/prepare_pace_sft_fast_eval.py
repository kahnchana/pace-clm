#!/usr/bin/env python3
"""Freeze a task-stratified 200-case benchmark and unchanged native inputs."""
import collections
import hashlib
import json
import random
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
PARENT=ROOT/'outputs/jevany-qwen35-2b-pace-estp-sft/base-50-50-b384-prefetch-v2-16h'
SOURCE=ROOT/'outputs/jevany-2b-rl/mixed-web-ego-estp-episode-balanced-v3-to128'
OUT=PARENT.with_name('eval-speed-design-v1')


def rows(p):return [json.loads(s) for s in p.read_text().splitlines() if s.strip()]
def dump(p,v):p.write_text(''.join(json.dumps(s,sort_keys=True)+'\n' for s in v))
def write(p,v):p.write_text(json.dumps(v,indent=2)+'\n')


def main():
    OUT.mkdir(exist_ok=False)
    for name in ['data','pilot','logs']:(OUT/name).mkdir()
    original=PARENT/'evaluation/corrected-step143'
    records=rows(ROOT/'outputs/jevany-2b-rl/mixed-web-ego-estp-balanced-v4-to160/evaluation/estp-explicit-step160/estp_pauc_explicit/explicit_manifest.jsonl')
    pools=collections.defaultdict(list)
    for record in records:pools[record['task_type']].append(record)
    selected=[];rng=random.Random(42)
    for task in sorted(pools):selected+=rng.sample(sorted(pools[task],key=lambda s:s['question_id']),25)
    assert len(selected)==200 and len({s['question_id'] for s in selected})==200
    qids={s['question_id'] for s in selected}
    bench_specs={f"{s['video_id']}/{s['clip_id']}/{s['qa_index']}":s for s in rows(SOURCE/'data/evaluation-specs.jsonl') if s.get('data_source')=='estp_bench'}
    specs=[s for s in rows(PARENT/'data/evaluation-specs.jsonl') if s['span_id'].startswith(('web:','ego:'))]
    specs+=[bench_specs[q] for q in sorted(qids)]
    by_span={s['span_id']:s for s in specs};ids=set(by_span)
    manifests={s['question_id']:s for s in rows(PARENT/'data/evaluation-manifest.jsonl') if s['question_id'] in ids}
    manifests.update({s['question_id']:s for s in rows(SOURCE/'data/evaluation-manifest.jsonl') if s['question_id'] in ids and s['question_id'] not in manifests})
    assert len(manifests)==1026==len(specs)
    dump(OUT/'data/estp-bench-explicit-200.jsonl',selected);dump(OUT/'data/specs.jsonl',specs)
    dump(OUT/'data/manifest.jsonl',[manifests[q] for q in sorted(ids)])
    # LPT assignment uses only input lengths, never decisions, answers or scores.
    bins=[[] for _ in range(8)];cost=[0]*8
    for spec in sorted(specs,key=lambda s:(-s['rollout_frames'],s['span_id'])):
        rank=min(range(8),key=lambda i:(cost[i],i));bins[rank].append(spec['span_id']);cost[rank]+=spec['rollout_frames']
    # Native evaluator assigns selection positions modulo eight. Fill long bins
    # first by final bin size, so shorter bins only disappear in the final row.
    order=sorted(range(8),key=lambda i:(-len(bins[i]),i));bins=[bins[i] for i in order];cost=[cost[i] for i in order]
    # Equal episode counts as well as balanced frame costs are needed for an
    # exact round-robin selection. Exchange cheap episodes from overfull bins.
    target=[len(specs)//8+(i<len(specs)%8) for i in range(8)]
    while any(len(bins[i])!=target[i] for i in range(8)):
        a=max((i for i in range(8) if len(bins[i])>target[i]),key=lambda i:len(bins[i])-target[i]);b=min((i for i in range(8) if len(bins[i])<target[i]),key=lambda i:cost[i])
        q=min(bins[a],key=lambda q:by_span[q]['rollout_frames']);bins[a].remove(q);bins[b].append(q);cost[a]-=by_span[q]['rollout_frames'];cost[b]+=by_span[q]['rollout_frames']
    selection=[bins[r][i] for i in range(max(target)) for r in range(8) if i<len(bins[r])]
    assert all(selection[r::8]==bins[r] for r in range(8))
    write(OUT/'data/selection.json',selection)
    populations={}
    for domain,prefix in [('web','web:'),('ego','ego:'),('estp-bench-explicit-200','estp-bench:')]:
        group=[s for s in specs if (s['span_id'].startswith(prefix) if domain!='estp-bench-explicit-200' else s.get('data_source')=='estp_bench')]
        populations[domain]=dict(episodes=len(group),unique_video_ids=len({s['video_id'] for s in group}),decisions=sum(s['rollout_frames'] for s in group))
    assert populations['web']['episodes']==500 and populations['ego']['episodes']==326 and populations['estp-bench-explicit-200']['episodes']==200
    write(OUT/'population.json',dict(sets=populations,task_counts={k:25 for k in sorted(pools)},seed=42,total_decisions=sum(cost),per_rank_decisions=cost,rank_episodes=target,
        protocol='Fixed task-stratified diagnostic subset, not the official full 851-case headline. Native whole episodes/windows; no length or score filtering.'))
    # Full reference trajectories already generated by the standard evaluator.
    web=rows(original/'web/rollout/predictions.jsonl');ego=rows(original/'ego/saved-predictions.jsonl')
    chosen=[min(web,key=lambda p:abs(len(p['jevany_action_trace'])-32))]
    eligible=[p for p in ego if len(p['model_response_list'])>=2 and p['model_response_list'][0]['time']<250]
    chosen.append(min(eligible,key=lambda p:p['question_id']))
    log=(original/'estp-bench-explicit/inference.log').read_text(errors='replace')
    done={q:int(f) for q,f in re.findall(r'\[rank \d+\] \d+/\d+ (\S+) fires=(\d+) elapsed=',log)}
    candidates=sorted([s for s in specs if s.get('data_source')=='estp_bench' and done.get(s['span_id'],0)>=2],key=lambda s:(abs(s['rollout_frames']-280),s['span_id']))[:2]
    wanted={s['span_id'] for s in candidates};found={}
    for path in sorted((original/'estp-bench-explicit/rollout').glob('predictions.rank*.jsonl')):
        with path.open() as handle:
            for line in handle:
                match=re.search(r'"question_id": "([^"\\]+)"',line)
                if match and match.group(1) in wanted:
                    p=json.loads(line);found[p['question_id']]=p
    assert set(found)==wanted and len(wanted)==2
    chosen+=[found[q] for q in sorted(wanted)];pilot_ids=[p['question_id'] for p in chosen]
    dump(OUT/'pilot/reference.jsonl',chosen);dump(OUT/'pilot/manifest.jsonl',[manifests[q] for q in pilot_ids]);write(OUT/'pilot/selection.json',pilot_ids)
    write(OUT/'data/input-hashes.json',{str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in (OUT/'data').glob('*') if p.is_file()})
    print(json.dumps(read_population(OUT)))


def read_population(out):return json.loads((out/'population.json').read_text())


if __name__=='__main__':main()
